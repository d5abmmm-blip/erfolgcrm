/**
 * Словарь типов техники для кнопок «какую технику обслуживает».
 *
 * Смысл теста — в одной мысли: навык инженера и тип техники должны быть ОДНИМИ И ТЕМИ
 * ЖЕ словами. Пока кнопки брались из выдуманного списка в коде («Кардиограф»), а на
 * технике из архива стоит «ЭКГ», совпадения не было бы никогда, сколько ни отмечай.
 *
 * Поэтому: реальный словарь (из базы, по частоте) — главный, выдуманный список
 * остаётся только на случай пустой базы у нового тенанта.
 */
import { describe, it, expect } from 'vitest';
import { COMMON_DEVICE_TYPES, deviceTypeOptions, nobodyHasSkill } from '../lib/device-types';

describe('кнопки типов техники', () => {
  it('реальный словарь идёт как есть — порядок по частоте не пересортировываем', () => {
    expect(deviceTypeOptions(['ЭКГ', 'ИВЛ', 'Стерилизатор'], [])).toEqual([
      'ЭКГ',
      'ИВЛ',
      'Стерилизатор',
    ]);
  });

  it('уже отмеченное человеку добавляется, даже если словарь о нём не знает', () => {
    expect(deviceTypeOptions(['ЭКГ'], ['Свой редкий аппарат'])).toEqual([
      'ЭКГ',
      'Свой редкий аппарат',
    ]);
  });

  it('дубли по регистру не плодятся', () => {
    expect(deviceTypeOptions(['ЭКГ'], ['экг'])).toEqual(['ЭКГ']);
  });

  it('пустая база — берём запасной список, чтобы кнопок не было ноль', () => {
    const out = deviceTypeOptions([], []);
    expect(out).toEqual([...COMMON_DEVICE_TYPES]);
  });

  it('когда словарь есть, запасной список не подмешиваем — иначе снова два словаря', () => {
    const out = deviceTypeOptions(['ЭКГ'], []);
    expect(out).not.toContain('Кардиограф');
  });
});

describe('никому не отмечена техника', () => {
  it('верно, когда навыка нет ни у кого', () => {
    expect(nobodyHasSkill([{ hasSkill: false }, { hasSkill: false }])).toBe(true);
  });

  it('неверно, когда хоть у кого-то есть', () => {
    expect(nobodyHasSkill([{ hasSkill: false }, { hasSkill: true }])).toBe(false);
  });

  it('неверно, когда тип техники неизвестен — сравнивать не с чем', () => {
    expect(nobodyHasSkill([{ hasSkill: null }, { hasSkill: null }])).toBe(false);
  });

  it('пустой список инженеров — не повод писать «ни у кого»', () => {
    expect(nobodyHasSkill([])).toBe(false);
  });
});
