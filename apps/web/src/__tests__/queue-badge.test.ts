/**
 * Очередь инженера (/m/queue): подпись «показано N из M» и догрузка.
 *
 * Находка аудита, ради которой это писалось: список молча обрезался на 100
 * заявках — ни счётчика, ни кнопки «ещё». У живых инженеров 416/404/359/331/
 * 288/269/249 заявок, то есть обрезало почти у каждого, и выглядело это как
 * «заявки нет».
 *
 * Плашка «Назначено новых» переехала со счёта количества на список заявок —
 * её проверки живут в `mobile-audit-small-fixes.test.ts` рядом с объяснением,
 * почему счёт по количеству молчал в самом частом случае.
 */
import { describe, it, expect } from 'vitest';
import { nextPageSize, shownOfTotal } from '../lib/queue-badge';

describe('подпись «показано N из M»', () => {
  it('молчит, когда показано всё', () => {
    expect(shownOfTotal(12, 12)).toBeNull();
    expect(shownOfTotal(50, 0)).toBeNull();
  });

  it('говорит, когда список обрезан — это и была жалоба', () => {
    expect(shownOfTotal(50, 416)).toBe('Показано 50 из 416');
  });
});

describe('догрузка', () => {
  it('растёт шагами', () => {
    expect(nextPageSize(50, 50, 500)).toBe(100);
    expect(nextPageSize(100, 50, 500)).toBe(150);
  });

  it('не просит у сервера больше, чем он отдаёт', () => {
    expect(nextPageSize(480, 50, 500)).toBe(500);
    expect(nextPageSize(500, 50, 500)).toBe(500);
  });

  it('доходит до 416 заявок самого загруженного инженера', () => {
    let n = 50;
    let шагов = 0;
    while (n < 416 && шагов < 50) {
      n = nextPageSize(n, 50, 500);
      шагов += 1;
    }
    expect(n).toBeGreaterThanOrEqual(416);
  });
});
