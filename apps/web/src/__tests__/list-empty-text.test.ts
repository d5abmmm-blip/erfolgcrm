/**
 * «Ничего нет» и «ничего не нашлось» — разные вещи.
 *
 * Списки клиентов, моделей и позиций склада при пустой выдаче писали «Клиентов пока
 * нет — добавьте первого». Но выдача пуста и когда в поиске набрано то, чего нет:
 * человек читал, что база пустая, при 665 клиентах в ней.
 */
import { describe, it, expect } from 'vitest';
import { listEmptyText } from '../lib/empty-text';

describe('listEmptyText', () => {
  it('поиск задан — говорим «не нашлось», а не «записей нет»', () => {
    const text = listEmptyText(true, 'Клиентов пока нет — добавьте первого');
    expect(text).not.toContain('добавьте первого');
    expect(text).toContain('не нашлось');
  });

  it('поиск пуст — список действительно пуст, зовём завести первую запись', () => {
    expect(listEmptyText(false, 'Клиентов пока нет — добавьте первого')).toBe(
      'Клиентов пока нет — добавьте первого',
    );
  });

  it('подсказку можно заменить своей', () => {
    expect(listEmptyText(true, 'нет', 'по этому серийнику ничего')).toBe(
      'по этому серийнику ничего',
    );
  });
});
