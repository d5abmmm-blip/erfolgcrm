/**
 * Подпись под пустым списком: «ничего нет» и «ничего не нашлось» — разные вещи.
 *
 * ЗАЧЕМ. Списки клиентов, моделей и позиций склада при пустой выдаче писали
 * «Клиентов пока нет — добавьте первого». Но выдача пуста и когда в поиске набрано
 * то, чего нет: человек читал, что база пустая, при 665 клиентах в ней. Дальше
 * начинается «программа потеряла клиентов».
 *
 * Правило: если задан поиск или фильтр — говорим «не нашлось», и подсказываем, что
 * дело в запросе. Если ничего не задано — список действительно пуст.
 */
export function listEmptyText(
  filtered: boolean,
  nothingYet: string,
  notFound = 'Ничего не нашлось — измените запрос или снимите фильтр',
): string {
  return filtered ? notFound : nothingYet;
}
