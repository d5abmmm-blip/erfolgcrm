/**
 * Кто сейчас за телефоном — одно значение на всё приложение.
 *
 * ЗАЧЕМ. Один телефон в бригаде переходит из рук в руки. Инженер А вышел,
 * не дождавшись связи; на том же телефоне вошёл Б — и накопленные правки А
 * уходили на сервер ОТ ИМЕНИ Б, вместе со строками наряда, от которых
 * считается зарплата.
 *
 * Теперь каждая запись очереди помнит автора, а отправляются только свои.
 * Чужие лежат и ждут своего человека: стирать их нельзя — это чужая работа.
 *
 * Держим отдельным крошечным хранилищем, а не тянем `auth.me` в очередь:
 * очередь работает и там, где нет ни React, ни tRPC-клиента.
 */
let currentUserId: string | null = null;

type Listener = () => void;
const listeners: Set<Listener> = new Set();

export function setCurrentUserId(id: string | null): void {
  if (currentUserId === id) return;
  currentUserId = id;
  // Очередь пересчитывает «что можно отправить» по автору записи, поэтому
  // смена человека — такое же событие, как изменение самой очереди. Без
  // оповещения накопленное «своё» лежало бы до первого касания очереди:
  // при запуске имя вошедшего приходит с сервера ПОЗЖЕ, чем автосинк
  // впервые смотрит на очередь, и в этот момент отправлять нельзя ничего.
  for (const l of listeners) {
    try {
      l();
    } catch {
      /* слушатель не должен ронять смену пользователя */
    }
  }
}

export function getCurrentUserId(): string | null {
  return currentUserId;
}

/** Подписка на смену человека за телефоном (вход/выход/другой сотрудник). */
export function subscribeCurrentUser(listener: Listener): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}
