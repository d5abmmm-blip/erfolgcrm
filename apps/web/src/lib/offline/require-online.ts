/**
 * Сбор файла (печать, Excel) требует связи — и проверять это надо ДО запроса.
 *
 * 🔴 ПОЧЕМУ НЕ «ПОПРОБУЕМ И ПОЙМАЕМ ОШИБКУ». У запросов режим `online`, и при
 * настоящем офлайне react-query не роняет запрос, а СТАВИТ ЕГО НА ПАУЗУ:
 * обещание не завершается никогда, `catch` и `finally` не срабатывают. Кнопка
 * навсегда остаётся в состоянии «Собираю…», и человек ждёт файл, которого не
 * будет. Ровно так намертво вешался сканер заявок (#112).
 *
 * Поэтому здесь не «обработка ошибки», а отказ идти в сеть: бросаем понятную
 * ошибку, которую уже умеют показать все четыре места сборки файлов.
 *
 * ⚠️ ГОЧА, стоившая времени раньше: выключенный сервер — это НЕ офлайн. Тогда
 * `navigator.onLine === true`, запрос уходит и честно падает, и его ловит
 * обычный `catch`. Эта проверка — только про потерянную связь.
 */
export class OfflineFileError extends Error {
  constructor(what: string) {
    super(`Нет связи с сервером: ${what} собрать не из чего. Попробуйте, когда связь вернётся.`);
    this.name = 'OfflineFileError';
  }
}

/**
 * Бросает `OfflineFileError`, если связи нет.
 *
 * @param what — что именно собирали, родительным падежом: «файл», «отчёт»,
 *   «счёт». Попадёт в текст сообщения человеку.
 */
export function assertOnlineForFile(what: string): void {
  if (typeof navigator !== 'undefined' && !navigator.onLine) {
    throw new OfflineFileError(what);
  }
}
