/**
 * Смена человека за телефоном: вход и выход стирают офлайн-память приложения.
 *
 * Один телефон в бригаде переходит из рук в руки. Без этого инженер Б, войдя
 * после инженера А, поднял бы из IndexedDB кэш А — чужую очередь и чужие
 * заявки. Плюс это простое обещание пользователю: «вышел — на телефоне ничего
 * не осталось».
 *
 * ПОЧЕМУ ЧИСТИМ И ПАМЯТЬ ВКЛАДКИ. Запись снимка отложенная (раз в секунду).
 * Сотрёшь только файл — и через мгновение отложенная запись вернёт всё обратно,
 * взяв данные из памяти вкладки, где ещё лежит очередь прошлого человека.
 *
 * ЧТО НЕ ТРОГАЕМ: очередь неотправленных правок. Её стирать нельзя — это
 * несохранённая работа инженера; она привязывается к автору отдельно.
 */
import type { QueryClient } from '@tanstack/react-query';
import { clearPersistedQueries } from './query-persist';

export async function resetOfflineMemory(queryClient: QueryClient): Promise<void> {
  queryClient.clear();
  await clearPersistedQueries();
}
