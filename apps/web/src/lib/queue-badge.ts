/**
 * Чистая логика экрана очереди инженера (/m/queue): плашка «Назначено новых»
 * и подпись «показано N из M».
 *
 * Вынесено из компонента, чтобы покрыть тестами: обе вещи легко ломаются
 * незаметно — плашка просто перестаёт появляться, а обрезанный список выглядит
 * как полный.
 */

/**
 * Ключ «какие заявки инженер уже видел».
 *
 * Ключ менялся дважды, и оба раза потому, что менялось само хранимое:
 * сначала это было число заявок со вкладки «Все» (сотни — плашка не
 * появлялась никогда), потом число активных, теперь СПИСОК идентификаторов.
 * Старые ключи не читаем: там лежит число, а не список.
 */
export function seenStorageKey(engineerId: string): string {
  return `m-queue-seen-ids-${engineerId}`;
}

/**
 * Какие заявки назначены с прошлого визита.
 *
 * СЧИТАЕМ ЗАЯВКИ, А НЕ ИХ КОЛИЧЕСТВО. Раньше сравнивались числа, и это молчало
 * в самом частом случае: инженер закрыл одну заявку, ему тут же назначили
 * другую — активных по-прежнему семь, разница ноль, плашки нет. Про новую
 * заявку он узнавал случайно.
 *
 * Берём активные заявки (отдельный запрос без пагинации), а не открытый
 * список: иначе плашка зависела бы от вкладки и от числа подгруженных страниц.
 *
 * `seen === null` — инженер на этом экране впервые: показывать «назначено
 * новых: 12» человеку, который просто открыл приложение, бессмысленно.
 */
export function newAssignmentIds(
  activeIds: readonly string[],
  seen: readonly string[] | null,
): string[] {
  if (seen === null) return [];
  const known = new Set(seen);
  return activeIds.filter((id) => !known.has(id));
}

/**
 * Прочитать отметку. null — её ещё нет или она испорчена: тогда это «первый
 * заход», и плашка молчит. Разбор строгий: пустая строка, не-JSON и список
 * не из строк читаются как «отметки нет», а не как «видел пустой список» —
 * иначе инженеру при первом же входе прилетело бы «назначено новых: 12».
 */
export function readSeenIds(raw: string | null): string[] | null {
  if (raw === null || raw.trim() === '') return null;
  try {
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return null;
    if (!parsed.every((v) => typeof v === 'string')) return null;
    return parsed;
  } catch {
    return null;
  }
}

/**
 * Подпись под списком. null — когда показано всё и говорить нечего.
 * Молчание при обрезанном списке и есть исходная жалоба: инженер решает,
 * что заявки нет, хотя она на следующей странице.
 */
export function shownOfTotal(shown: number, total: number): string | null {
  if (total <= shown) return null;
  return `Показано ${shown} из ${total}`;
}

/** Сколько ещё догрузить, чтобы не просить у сервера больше, чем он отдаёт. */
export function nextPageSize(current: number, step: number, max: number): number {
  return Math.min(max, current + step);
}
