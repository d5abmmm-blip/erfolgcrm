/**
 * Чистая логика экрана очереди инженера (/m/queue): плашка «Назначено новых»
 * и подпись «показано N из M».
 *
 * Вынесено из компонента, чтобы покрыть тестами: обе вещи легко ломаются
 * незаметно — плашка просто перестаёт появляться, а обрезанный список выглядит
 * как полный.
 */

/**
 * Ключ «сколько заявок инженер уже видел».
 *
 * Намеренно НЕ тот, что был раньше (`m-queue-seen-<id>`): в старом ключе лежит
 * общее число заявок со вкладки «Все» — у живых инженеров это сотни. Считать
 * от него разницу означает, что плашка не появится уже никогда. Новый ключ
 * начинает счёт заново и хранит число АКТИВНЫХ заявок.
 */
export function seenStorageKey(engineerId: string): string {
  return `m-queue-seen-active-${engineerId}`;
}

/**
 * Сколько заявок назначено с прошлого визита.
 *
 * Считается от числа АКТИВНЫХ заявок, а не от размера открытого списка:
 * иначе плашка зависела бы от выбранной вкладки и от того, сколько страниц
 * подгрузил человек. Архив («Все») растёт только вверх и к «назначено новых»
 * отношения не имеет.
 *
 * `seen === null` — инженер на этом экране впервые: показывать «назначено
 * новых: 12» человеку, который просто открыл приложение, бессмысленно.
 */
export function newAssignmentsCount(activeCount: number, seen: number | null): number {
  if (seen === null) return 0;
  return Math.max(0, activeCount - seen);
}

/**
 * Прочитать отметку. Возвращает null, если её ещё нет или она испорчена.
 * Пустую строку отсекаем явно: Number('') === 0, и без этой проверки пустое
 * значение читалось бы как «видел 0 заявок» вместо «первый заход».
 */
export function readSeen(raw: string | null): number | null {
  if (raw === null || raw.trim() === '') return null;
  const n = Number(raw);
  return Number.isFinite(n) && n >= 0 ? n : null;
}

/**
 * Подпись под списком. null — когда показано всё и говорить нечего.
 * Молчание при обрезанном списке и есть исходная жалоба: инженер решает,
 * что заявки нет, хотя она на следующей странице.
 */
export function shownOfTotal(shown: number, total: number): string | null {
  if (total <= shown) return null;
  return `Показано ${shown} из ${total}`;
}

/** Сколько ещё догрузить, чтобы не просить у сервера больше, чем он отдаёт. */
export function nextPageSize(current: number, step: number, max: number): number {
  return Math.min(max, current + step);
}

/**
 * Новое значение отметки, если его нужно опустить, иначе null.
 *
 * Инженер закрыл заявки — активных стало меньше запомненного. Если отметку не
 * опустить, следующие назначения будут «съедаться» устаревшим порогом: было
 * 60, закрыл 25 → активных 38; назначили новую → 39, и 39 − 60 = 0, плашка
 * молчит. Ровно та болезнь, что и в исходной находке, только мельче.
 */
export function rebasedSeen(activeCount: number, seen: number | null): number | null {
  if (seen === null || activeCount >= seen) return null;
  return activeCount;
}
