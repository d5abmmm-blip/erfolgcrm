/**
 * Единое определение «Итого» строки зарплатной ведомости.
 *
 * Итог к выплате = начислено (оклад + сделка + премия) МИНУС уже выданный аванс.
 * Аванс — это деньги, выданные сотруднику раньше (в середине месяца), поэтому он
 * уменьшает остаток к доплате, а не увеличивает его.
 *
 * Одна функция на все места: строка сотрудника, итоговая строка «Всего», годовая
 * сводка и сумма, которая проводится в кассу. Работает и в рублях, и в копейках —
 * это просто арифметика над четырьмя числами.
 */
export function vedomostNetTotal(parts: {
  salary: number;
  piecework: number;
  bonus: number;
  advance: number;
}): number {
  return parts.salary + parts.piecework + parts.bonus - parts.advance;
}
