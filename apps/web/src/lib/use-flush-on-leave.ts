/**
 * «Экран уходит — запиши, что набрано».
 *
 * ЗАЧЕМ. Наряд пишется по уходу курсора из поля, и это единственный момент
 * записи. Но телефонное «назад» и сворачивание приложения курсор из поля не
 * выводят: экран просто убирают. Набранное оставалось в оперативной памяти
 * вкладки и исчезало вместе с ней — молча, вместе с деньгами (строка наряда
 * кормит и счёт клиенту, и сделку в зарплате).
 *
 * ТРИ МОМЕНТА УХОДА:
 *  - размонтирование — «назад» внутри приложения, самый частый случай;
 *  - `visibilitychange` → hidden — свернул приложение, заблокировал телефон;
 *  - `pagehide` — вкладку закрывают или система выгружает PWA.
 *
 * 🔴 ЧЕГО ЭТОТ ПРИЁМ НЕ УМЕЕТ — ИЗМЕРЕНО В ЖИВОМ БРАУЗЕРЕ, А НЕ ПРЕДПОЛОЖЕНО.
 * Первые два случая доезжают: страница остаётся жить, и запись успевает лечь
 * в очередь. **А вот при НАСТОЯЩЕЙ выгрузке страницы текст теряется до сих
 * пор**: `pagehide` срабатывает, но запись в IndexedDB асинхронная и умирает
 * вместе со страницей — проверено навигацией с набранным текстом, очередь
 * после неё осталась пустой. Слушателя оставляем (при заморозке вкладки
 * страница переживает событие и запись доходит), но полагаться на него нельзя.
 *
 * Закроет дыру только СИНХРОННАЯ запись черновика (localStorage) на каждую
 * букву плюс восстановление при возврате на экран — это отдельная работа.
 *
 * ВАЖНО ДЛЯ ВЫЗЫВАЮЩЕГО: `flush` обязан сам проверять, изменилось ли что-то.
 * Запись «всегда при уходе» слала бы пустые правки при каждом открытии
 * карточки, а у строк наряда — ещё и дубли, то есть задвоенные деньги.
 */
import { useEffect, useRef } from 'react';

export function useFlushOnLeave(flush: () => void): void {
  // Держим в ref: подписываемся один раз, а вызвать нужно САМУЮ СВЕЖУЮ
  // версию — она замкнута на текущий текст в поле.
  const latest = useRef(flush);
  latest.current = flush;

  useEffect(() => {
    const onVisibility = () => {
      if (document.visibilityState === 'hidden') latest.current();
    };
    const onPageHide = () => latest.current();

    document.addEventListener('visibilitychange', onVisibility);
    window.addEventListener('pagehide', onPageHide);

    return () => {
      document.removeEventListener('visibilitychange', onVisibility);
      window.removeEventListener('pagehide', onPageHide);
      // Размонтирование — это тоже уход с экрана, и самый частый.
      latest.current();
    };
  }, []);
}
