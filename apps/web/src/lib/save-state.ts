/**
 * Состояние записи одного поля — то, чего инженеру не хватало.
 *
 * ЗАЧЕМ. Наряд разговаривал с человеком ТОЛЬКО когда плохо: при удачном
 * сохранении не показывалось ничего — ни галочки, ни надписи. Тишина означала
 * «записано», а читалась как «пропало». Причём на соседнем экране за
 * комментарий тот же инженер получает зелёное «Комментарий добавлен» — то есть
 * он приучен, что зелёное = сохранено, и молчание наряда читает как отказ.
 *
 * Отсюда и жалоба «нет кнопки сохранить»: кнопки нет, потому что запись идёт
 * по уходу курсора, — но настоящая беда в том, что о результате не сообщают.
 *
 * Слова подобраны честно и по-разному:
 *   «записано»    — сервер принял, работа на месте;
 *   «ждёт связи»  — лежит в телефоне, уйдёт само; НЕ «сохранено», потому что
 *                   на сервере этого ещё нет, и обещать нельзя.
 */
export type SaveMarkState = 'idle' | 'saving' | 'saved' | 'queued';

/** Сколько держим зелёную отметку, прежде чем убрать её с глаз. */
export const SAVED_MARK_MS = 2_500;

export interface SaveMarkLabel {
  text: string;
  tone: 'muted' | 'success' | 'warning';
}

export function saveMarkLabel(state: SaveMarkState): SaveMarkLabel | null {
  switch (state) {
    case 'saving':
      return { text: 'записываю…', tone: 'muted' };
    case 'saved':
      return { text: 'записано', tone: 'success' };
    case 'queued':
      // Тот же смысл, что и у прежней подписи в строке наряда: на сервер
      // ещё не ушло, но и не потеряно.
      return { text: 'ждёт связи — отправится само', tone: 'warning' };
    default:
      return null;
  }
}

/** Исход `executeOrQueue` → состояние отметки. Ошибку показывает тост, не отметка. */
export function saveMarkFromResult(status: 'ok' | 'queued' | 'error'): SaveMarkState {
  if (status === 'ok') return 'saved';
  if (status === 'queued') return 'queued';
  return 'idle';
}
