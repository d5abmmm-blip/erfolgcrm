import { SILENT_ERROR } from './error-message';

/**
 * Настройки запросов и мутаций, общие для приложения и для тестов.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Одна из этих настроек — `networkMode: 'always'`
 * у мутаций — держит на себе ВСЮ офлайн-очередь. Если тест поднимает свой
 * QueryClient «как в приложении», но без неё, он проверяет не то приложение,
 * которое установлено у инженера. Так и вышло: очередь считалась рабочей
 * годами, а при настоящем офлайне не срабатывала ни разу.
 */

/**
 * ПОЧЕМУ 'always' У МУТАЦИЙ.
 *
 * По умолчанию react-query при пропаже связи мутацию НЕ отправляет, а
 * СТАВИТ НА ПАУЗУ: обещание `mutateAsync` не отклоняется и не выполняется —
 * оно висит вечно. А вся офлайн-очередь построена на том, что отправка
 * УПАДЁТ, и в `catch` сработает постановка в очередь (см. executeOrQueue).
 *
 * На телефоне инженера это выглядело так: в подвале он жмёт «Сохранить
 * комментарий», кнопка крутится бесконечно, в очередь не кладётся ничего,
 * и отправлять при возврате связи нечего.
 *
 * Почему не замечали: и тесты, и живые проверки гасили СЕРВЕР, а сеть у
 * машины оставалась — тогда `navigator.onLine === true`, react-query считает
 * связь живой, запрос честно падает, и очередь работает. Настоящий офлайн
 * (радио выключено) ведёт себя иначе.
 *
 * С 'always' мутация уходит всегда и сразу падает на fetch — это и нужно:
 * решение «в очередь или показать ошибку» принимает наш код, а не библиотека.
 */
export const MUTATION_DEFAULTS = {
  networkMode: 'always',
} as const;

/**
 * У ЗАПРОСОВ ПАУЗА, НАОБОРОТ, НУЖНА.
 *
 * `fetchStatus === 'paused'` — это то, по чему экраны отличают «нет связи»
 * от «сервер ответил пусто». На нём держатся плашки «Не удалось загрузить …
 * Нет связи с сервером — загрузка приостановлена». Поэтому здесь режим по
 * умолчанию не трогаем.
 */
export const QUERY_DEFAULTS = {
  staleTime: 30_000,
  refetchOnWindowFocus: false,
  retry: 1,
} as const;

/**
 * Пометка для мутаций, обёрнутых в `executeOrQueue`.
 *
 * Такая мутация ВСЕГДА разбирается со своей ошибкой сама: при пропаже связи
 * она уходит в очередь и экран говорит «сохранено в очередь, отправится
 * автоматически»; при отказе по существу экран показывает свой текст.
 * Общий перехватчик ошибок мутаций (main.tsx) в этот момент лишний — он
 * говорит «Нет связи с сервером. Изменение не сохранено», то есть прямо
 * противоположное правде.
 *
 * Раньше этого не было видно: react-query при офлайне мутацию не отправлял
 * вовсе (ставил на паузу), ошибки не возникало — и перехватчик молчал.
 * Как только очередь начала работать по-настоящему, вылезли оба сообщения
 * сразу, и они противоречат друг другу.
 *
 * Сам признак берём из существующего `SILENT_ERROR` — второе имя для того же
 * флага рано или поздно разъехалось бы с первым.
 */
export const QUEUED_MUTATION = { meta: SILENT_ERROR } as const;
