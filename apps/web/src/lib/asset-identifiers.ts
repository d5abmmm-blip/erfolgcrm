/**
 * Единое определение того, как аппарат подписан на экране.
 *
 * У техники два номера, и оба необязательные:
 *   • серийный (S/N) — заводской, есть у большинства;
 *   • инвентарный — номер бирки клиента. У бюджетников (военные части,
 *     госбольницы) он ЕДИНСТВЕННЫЙ: серийник менеджеру просто не сообщают.
 *
 * Раньше экраны показывали только серийник, поэтому у «инвентарных» заказчиков
 * инженер видел одну модель и опознать аппарат не мог. Показываем оба, если оба
 * есть; если нет ни одного — пустая строка, чтобы не рисовать « · » впустую.
 *
 * Одна функция на все места: карточка заявки инженера, очередь, список заявок,
 * подбор техники, глобальный поиск.
 */
export function assetIdentifierLine(a: {
  serialNumber?: string | null;
  inventoryNumber?: string | null;
}): string {
  const parts: string[] = [];
  // trim: у импортированных из WinServisePro и при ручном вводе вместо NULL
  // нередко лежат пробелы — это «номера нет», а не номер из пробелов.
  const serial = a.serialNumber?.trim();
  const inventory = a.inventoryNumber?.trim();
  if (serial) parts.push(`S/N ${serial}`);
  if (inventory) parts.push(`инв. № ${inventory}`);
  return parts.join(' · ');
}
