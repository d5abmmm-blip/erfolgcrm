/**
 * Признак «запись из старой системы» на стороне БД.
 *
 * Определение ОДНО на всю систему и живёт в `@erfolg/shared/legacy-origin` — там же
 * измерения, доказывающие, что признак точен (импорт выдаёт идентификаторы версии 5,
 * приложение — 4 и 7; расхождений на боевой копии ноль). Здесь только зеркало для SQL.
 *
 * ⚠️ ГЛАВНОЕ ПРАВИЛО: признаком ПОМЕЧАЮТ, а не прячут.
 *
 * Что стоит на импортированных данных (проверено 2026-08-15):
 *   • ВСЯ себестоимость системы — 22 наряда на 137 056 ₽ лежат в шапках
 *     импортированных нарядов, больше её взять негде;
 *   • тип техники для 85 % карточек выводится из `repair_archive`;
 *   • графики ТО и гарантии висят на импортированной технике — своей почти нет;
 *   • выгрузка в 1С берёт контрагентов из импортированных клиентов;
 *   • поиск по серийнику и штрих-коду — это сканер инженера: спрятать импорт значит
 *     ответить «не найдено» на существующий аппарат.
 *
 * Поэтому фильтровать по этому признаку можно ровно там, где вопрос звучит как
 * «сколько работы у людей СЕЙЧАС»: доска, дашборд, отчёт загрузки, ассистент. Деньги,
 * поиск, техника, ТО, 1С и история клиента — не трогать.
 */
import { sql, type SQL } from 'drizzle-orm';
import type { AnyColumn } from 'drizzle-orm';

/**
 * SQL-условие «эта запись перенесена из старой системы» — по версии идентификатора.
 * Зеркало `isLegacyId` из @erfolg/shared: версия записана в 15-м символе.
 */
export function isLegacyIdSql(column: AnyColumn): SQL {
  return sql`substring(${column}::text, 15, 1) = '5'`;
}

/** Обратное условие — «запись заведена в самой CRM». */
export function isOwnIdSql(column: AnyColumn): SQL {
  return sql`substring(${column}::text, 15, 1) <> '5'`;
}
