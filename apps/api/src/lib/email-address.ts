/**
 * Проверка, что строка вообще похожа на почтовый адрес.
 *
 * ЗАЧЕМ. В поле `clients.email` из старой системы (WinServisePro) приехал СВОБОДНЫЙ ТЕКСТ:
 * имена («Магомед»), телефоны («8964…»), обрывки. На проде 2026-07-22 из 43 непустых
 * значений **39 были без «@»** — то есть настоящих адресов всего 4.
 *
 * Проверки «поле не пустое» для отправки НЕДОСТАТОЧНО: непустой мусор доезжает до
 * nodemailer, тот падает с `No recipients defined`, задача уходит в ретраи, и пять смен
 * статуса за утро дают 24 ошибки в логах. Для человека это выглядит как «почта сломалась»,
 * хотя сломаны данные в карточке клиента.
 *
 * Регулярка намеренно ТА ЖЕ, что уже применяется в `modules/email/ai-draft.ts` —
 * не заводим второе, расходящееся определение «валидного адреса». Она нарочно
 * нестрогая: задача — отсечь заведомо не-адреса, а не сверяться с RFC 5322.
 * Строгая проверка отбраковала бы живые адреса, и письма перестали бы уходить.
 */
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

/**
 * Похоже ли значение на адрес, по которому имеет смысл пытаться отправить письмо.
 * `null` / пусто / пробелы / текст без «@» → false.
 */
export function isEmailAddress(value: string | null | undefined): boolean {
  if (!value) return false;
  return EMAIL_RE.test(value.trim());
}

/**
 * Пригодный для отправки адрес или `null`.
 * Заодно подрезает пробелы по краям — в импортированных данных они встречаются.
 */
export function normalizeEmailAddress(value: string | null | undefined): string | null {
  if (!value) return null;
  const trimmed = value.trim();
  return EMAIL_RE.test(trimmed) ? trimmed : null;
}
