/**
 * Разбор того, что инженер написал своими словами, на «Диагноз» и «Описание
 * ремонта» — путь БЕЗ модели.
 *
 * Запрос владельца 2026-08-08: инженеры не любят приложение, контакт с ним надо
 * сократить. Они пишут одной кучей «что сломалось и что сделал», а программа
 * должна разложить это по полям и причесать. Когда LLM подключён — раскладывает
 * он; сейчас у владельца кончились токены, и работает этот разбор.
 *
 * Главное требование, ради которого тесты и написаны: НИЧЕГО НЕ ВЫДУМЫВАТЬ.
 * Текст уходит в акт, который подписывает клиент. Ни гарантий, ни сроков, ни
 * «протестировано» там, где инженер этого не говорил.
 */
import { describe, expect, it } from 'vitest';
import {
  classifyClause,
  composeFromNotes,
  inventsFacts,
  parseComposedJson,
} from '../modules/work-orders/compose-notes';

describe('инженер написал как умеет — раскладываем по полям', () => {
  it('«плата сгорела поменял всё пашет» → поломка отдельно, работа отдельно', () => {
    const r = composeFromNotes('плата сгорела поменял всё пашет');
    expect(r.diagnosis).toBe('Плата сгорела.');
    expect(r.repairDescription).toContain('Заменил');
    // Итог — СЛОВАМИ ИНЖЕНЕРА («всё пашет» → «работает исправно»), а не нашей
    // выдуманной фразой про протестированность (см. «ничего не выдумываем»).
    expect(r.repairDescription).toContain('Работает исправно');
  });

  it('просторечие уходит: «сдох», «не пашет», «поменял»', () => {
    const r = composeFromNotes('не включается вообще, блок питания сдох, поменял, работает');
    expect(r.diagnosis).toMatch(/не включается/i);
    expect(r.diagnosis).toMatch(/вышел из строя/i);
    expect(r.diagnosis).not.toMatch(/сдох/i);
    expect(r.repairDescription).toMatch(/заменил/i);
    expect(r.repairDescription).not.toMatch(/поменял/i);
  });

  it('выезд и осмотр — это работа, а не диагноз', () => {
    // «не нашёл» содержит признак поломки, но фраза целиком — отчёт о работе.
    const r = composeFromNotes('приехал посмотрел ничего не нашел все работает');
    expect(r.diagnosis).toBeNull();
    // Два действия — два предложения. Раньше выходило одно, «Приехал осмотрел»:
    // граница после «приехал» не ставилась из-за той же беды с хвостовой «л»
    // (см. ниже «глагол-действие начинает мысль»). Отдельными фразами и
    // читается лучше, и главное не меняется — это работа, а не диагноз.
    expect(r.repairDescription).toMatch(/Приехал\.\s*Осмотрел/i);
  });
});

/**
 * Две ошибки, пойманные пробой на живых фразах (тесты их не показывали) —
 * закреплены, чтобы не вернулись.
 */
describe('ловушки разбора', () => {
  it('поломка находится по основе слова, а не по точному совпадению', () => {
    // Была ошибка приоритета в регулярке: `сгор|...|X[а-я]*` вешает хвост
    // только на ПОСЛЕДНЮЮ ветку, поэтому «сгор» требовало слова ровно «сгор»,
    // «сгорела» не находилось — и поломка молча уезжала в описание работ.
    expect(composeFromNotes('плата сгорела').diagnosis).toBe('Плата сгорела.');
    expect(composeFromNotes('шланг потек').diagnosis).toMatch(/потек/i);
    expect(composeFromNotes('подшипник полетел').diagnosis).toMatch(/вышел из строя/i);
  });

  it('новую мысль начинает только глагол прошедшего времени', () => {
    // Была ошибка: резало перед существительным «поставку» (основа «постав»),
    // и получалось «Заказал плату жду. Поставку.».
    const r = composeFromNotes('заказал плату жду поставку');
    expect(r.repairDescription).toBe('Заказал плату жду поставку.');
  });

  it('глагол-действие начинает мысль, даже если его основа сама кончается на «л»', () => {
    // Найдено пробой на живых фразах. Граница мысли требует «л» ПОСЛЕ основы,
    // а в списке лежали целые слова «заказал», «осмотрел», «вернул» — им эту
    // «л» приписать было неоткуда, и граница не ставилась. Итог: отчёт о
    // работе уезжал в «Диагноз», то есть в акте клиент читал про поломку
    // ровно то, что инженер сделал.
    const r = composeFromNotes('не греет вообще заказал плату жду поставку');
    expect(r.diagnosis).toBe('Не греет вообще.');
    expect(r.repairDescription).toMatch(/Заказал плату жду поставку/i);
  });

  it('обрывки-пустышки в поля не попадают', () => {
    // «вроде норм» резалось перед словом об итоге, и в «Описании ремонта»
    // оставалось предложение «Вроде.» — в акте это выглядит как небрежность.
    const r = composeFromNotes('почистил шлейф, подтянул разъем, вроде норм');
    expect(r.repairDescription).not.toMatch(/(^|\s)Вроде\./);
    expect(r.repairDescription).toMatch(/Очистил шлейф/i);
  });

  it('падеж дополнения не ломается: меняем глагол на глагол, а не на существительное', () => {
    // «поменял плату» → «заменил плату», а НЕ «произведена замена плату».
    const r = composeFromNotes('поменял плату питания');
    expect(r.repairDescription).toContain('Заменил плату питания');
  });
});

/**
 * Самое опасное место. Фраза «оборудование протестировано, работоспособность
 * восстановлена» — это утверждение в документе. Дописать её к «жду запчасть»
 * значит соврать клиенту от имени инженера.
 */
describe('ничего не выдумываем', () => {
  it('нет слов про «работает» — нет и фразы про восстановленную работоспособность', () => {
    const r = composeFromNotes('заказал плату, жду поставку');
    expect(r.repairDescription).not.toMatch(/работоспособность/i);
    expect(r.repairDescription).not.toMatch(/протестировано/i);
  });

  /**
   * ⚠️ САМАЯ ДОРОГАЯ ОШИБКА ЭТОГО ФАЙЛА, найдена состязательным разбором.
   *
   * Фразу дописывал любой намёк на итог — «норм», «всё», — и в акт уходило
   * утверждение о ПРОЦЕДУРЕ (протестировано) и о РЕЗУЛЬТАТЕ (работоспособность
   * восстановлена), которых инженер не говорил. «Жду запчасть, пока норм»
   * превращалось в «работоспособность восстановлена» — прямая ложь клиенту,
   * под которой он ставит подпись.
   *
   * Теперь своих утверждений не дописываем ВООБСЕ: слова инженера об итоге
   * идут в текст как есть, причёсанные словарём. Красиво напишет модель.
   */
  it('инженер ждёт запчасть, а в акте «восстановлена работоспособность» — так нельзя', () => {
    const r = composeFromNotes('жду запчасть, пока норм');
    expect(r.repairDescription).not.toMatch(/протестировано/i);
    expect(r.repairDescription).not.toMatch(/работоспособность/i);
    expect(r.repairDescription).toMatch(/жду запчасть/i);
  });

  it('«снял плату, всё» — «всё» это «закончил», а не «всё работает»', () => {
    const r = composeFromNotes('снял плату, всё');
    expect(r.repairDescription).not.toMatch(/протестировано|работоспособность/i);
  });

  it('слова инженера об итоге сохраняются — но своими, а не нашими', () => {
    const r = composeFromNotes('плата сгорела поменял всё пашет');
    expect(r.diagnosis).toBe('Плата сгорела.');
    expect(r.repairDescription).toMatch(/заменил/i);
    // Он сказал «всё пашет» → «работает исправно». Он НЕ говорил «протестировано».
    expect(r.repairDescription).toMatch(/работает исправно/i);
    expect(r.repairDescription).not.toMatch(/протестировано/i);
  });

  it('в ответе нет ничего, чего не было во входе: ни гарантий, ни сроков, ни цен', () => {
    const r = composeFromNotes('почистил оптику');
    const all = `${r.diagnosis ?? ''} ${r.repairDescription ?? ''}`;
    expect(all).not.toMatch(/гаранти/i);
    expect(all).not.toMatch(/\d+\s*(мес|дн|год)/i);
    expect(all).not.toMatch(/руб|₽/);
  });

  it('пустой ввод — пустой ответ, а не «работы выполнены в полном объёме»', () => {
    expect(composeFromNotes('')).toEqual({ diagnosis: null, repairDescription: null });
    expect(composeFromNotes('   ')).toEqual({ diagnosis: null, repairDescription: null });
  });
});

describe('когда сказано только про одно', () => {
  it('только поломка — описание ремонта пустое, а не выдуманное', () => {
    const r = composeFromNotes('не греет');
    expect(r.diagnosis).toBe('Не греет.');
    expect(r.repairDescription).toBeNull();
  });

  it('только работа — диагноз пустой', () => {
    const r = composeFromNotes('почистил оптику');
    expect(r.diagnosis).toBeNull();
    expect(r.repairDescription).toBe('Очистил оптику.');
  });
});

/**
 * «Не работает» — самая частая фраза инженера вообще. Найдено состязательным
 * разбором: слово «работает» открывало новую мысль ДАЖЕ после «не», фраза
 * разваливалась пополам, поломка исчезала из диагноза, а в «Описание ремонта»
 * уходил обрывок «Не.» — и следом фраза о восстановленной работоспособности.
 */
describe('отрицание не отрывается от слова', () => {
  it('«не работает» остаётся поломкой целиком', () => {
    const r = composeFromNotes('не работает');
    expect(r.diagnosis).toBe('Не работает.');
    expect(r.repairDescription).toBeNull();
  });

  it('«аппарат не работает поменял плату» — поломка и работа по своим местам', () => {
    const r = composeFromNotes('аппарат не работает поменял плату');
    expect(r.diagnosis).toMatch(/аппарат не работает/i);
    expect(r.repairDescription).toMatch(/заменил плату/i);
    // Обрывка «Не.» не остаётся нигде.
    expect(`${r.diagnosis} ${r.repairDescription}`).not.toMatch(/(^|\s)Не\.(\s|$)/);
  });

  it('оговорку инженера не превращаем в утверждение', () => {
    // «вроде норм» слабее, чем «норм». Выбросить «вроде» — усилить сказанное.
    const r = composeFromNotes('заказал плату вроде норм');
    expect(r.repairDescription).toMatch(/вроде норм/i);
  });
});

/**
 * Сторож за моделью. Найдено состязательным разбором: числа сверялись
 * ПОДСТРОКОЙ всего исходника, поэтому «6» находилось внутри инвентарного
 * номера «6472», а «5» — внутри «250в». Выдуманная гарантия проходила ровно
 * там, где инженер написал хоть какие-то цифры, — то есть почти всегда.
 */
describe('сторож за моделью считает числа числами', () => {
  it('инвентарный номер не разрешает выдумать срок гарантии', () => {
    expect(inventsFacts('поменял плату инв 6472', 'Заменена плата. Гарантия 6 месяцев.')).toBe(
      true,
    );
    expect(inventsFacts('поменял предохранитель 250в', 'Заменён предохранитель. Срок 5 лет.')).toBe(
      true,
    );
  });

  it('числа, которые инженер написал сам, модели не запрещены', () => {
    expect(inventsFacts('полетели 2 подшипника', 'Заменены 2 подшипника.')).toBe(false);
    expect(inventsFacts('поменял предохранитель 250в', 'Заменён предохранитель 250в.')).toBe(false);
  });

  it('«два» и «2» — одно и то же, честный ответ модели не бракуем', () => {
    // Иначе модель, написавшая цифрой то, что инженер написал словом,
    // объявлялась выдумщицей — и человек читал «ИИ не настроен», хотя настроен.
    expect(inventsFacts('поменял два подшипника', 'Заменены 2 подшипника.')).toBe(false);
    expect(inventsFacts('снял три платы', 'Сняты 3 платы.')).toBe(false);
  });

  it('гарантия и деньги, которых не было во входе', () => {
    expect(inventsFacts('поменял плату', 'Заменена плата. Гарантия предоставлена.')).toBe(true);
    expect(inventsFacts('поменял плату', 'Заменена плата. Стоимость 5000 руб.')).toBe(true);
  });
});

describe('разбор ответа модели', () => {
  it('слово «null» строкой — это пусто, а не текст диагноза', () => {
    // Модели отдают такое регулярно. В акте печаталось бы слово «null».
    const r = parseComposedJson('{"diagnosis":"null","repairDescription":"Плата заменена."}');
    expect(r?.diagnosis).toBeNull();
    expect(r?.repairDescription).toBe('Плата заменена.');
  });

  it('прочерк вместо текста — тоже пусто', () => {
    const r = parseComposedJson('{"diagnosis":"—","repairDescription":"Плата заменена."}');
    expect(r?.diagnosis).toBeNull();
  });

  it('оба поля пустые — ответ не годится, пусть работает разбор без модели', () => {
    expect(parseComposedJson('{"diagnosis":null,"repairDescription":null}')).toBeNull();
    expect(parseComposedJson('{"diagnosis":"null","repairDescription":"-"}')).toBeNull();
  });
});

describe('разбор клауз', () => {
  it('«не включается» — поломка, «заменил плату» — работа', () => {
    expect(classifyClause('не включается')).toBe('problem');
    expect(classifyClause('заменил плату')).toBe('action');
    expect(classifyClause('работает')).toBe('result');
  });

  it('непонятное относим к работам — там оно безопаснее, чем в диагнозе', () => {
    expect(classifyClause('шлейф у разъёма')).toBe('action');
  });
});
