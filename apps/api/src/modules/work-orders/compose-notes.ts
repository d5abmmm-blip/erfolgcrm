/**
 * Инженер пишет одной кучей и своими словами — программа раскладывает это
 * на «Диагноз» и «Описание ремонта».
 *
 * ЗАЧЕМ. Запрос владельца 2026-08-08: «инженеры вообще не любят мобильное
 * приложение, надо минимизировать их контакт с программой. Они по-своему,
 * по-колхозному пишут, что сломалось и что сделали, а ИИ грамотно
 * перефразирует». Сегодня полей три и заполнять их надо руками; кнопка
 * «ИИ-черновик» при этом текст инженера НЕ ЧИТАЕТ — она собирает свой из
 * строк наряда и затирает написанное.
 *
 * ЭТОТ ФАЙЛ — ПУТЬ БЕЗ МОДЕЛИ. Когда LLM настроен, раскладывает он (см.
 * service.ts). Когда модели нет — а прямо сейчас у владельца кончились
 * токены — работает этот разбор. Он не притворяется ИИ, а делает то немногое,
 * что можно сделать честно и предсказуемо:
 *
 *   1. делит написанное на «что было» и «что сделал»;
 *   2. убирает просторечие по словарю целых слов;
 *   3. приводит заглавные буквы и точки.
 *
 * ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ — выдумывания. Ни одного факта, которого нет во
 * входном тексте: ни гарантий, ни сроков, ни моделей, ни цен. Текст уходит
 * в акт, который подписывает клиент.
 *
 * ДВЕ ЛОВУШКИ, НА КОТОРЫХ ЭТОТ РАЗБОР УЖЕ ЛОМАЛСЯ:
 *
 * 1. `\b` В JAVASCRIPT НЕ РАБОТАЕТ С КИРИЛЛИЦЕЙ. `\w` — это латиница, поэтому
 *    `\bпоменял\b` не находит «поменял». Границу слова задаём сами, через
 *    просмотр назад и вперёд по русским буквам (`edge`).
 * 2. ИНЖЕНЕР НЕ СТАВИТ ЗНАКОВ ПРЕПИНАНИЯ. «плата сгорела поменял всё пашет» —
 *    это три мысли в одной строке. Резать только по точкам и запятым нельзя:
 *    получится одна клауза, и всё уедет в одно поле. Поэтому границу ставим
 *    ещё и перед словом-действием и перед словами об итоге.
 *
 * ПОЧЕМУ ЗАМЕНЫ ТОЛЬКО «БЕЗОПАСНЫЕ ПО ПАДЕЖУ». «поменял плату» → «заменил
 * плату» правильно, а «поменял плату» → «произведена замена плату» — мусор.
 * Поэтому глаголы меняем только на глаголы того же управления, а не на
 * отглагольные существительные. Красиво и безлично напишет модель, когда
 * появится; наша задача — не испортить.
 */

export interface ComposedNotes {
  /** «Что было» — в поле «Диагноз». null, если про поломку ничего не сказано. */
  diagnosis: string | null;
  /** «Что сделал» — в поле «Описание ремонта». null, если про работы молчок. */
  repairDescription: string | null;
}

/** Русские и латинские буквы — из них состоит «слово» для границ. */
const LETTER = 'а-яёА-ЯЁa-zA-Z';

/** Регулярка на целое слово: `\b` с кириллицей не работает (см. шапку файла). */
function edge(pattern: string, flags = 'gi'): RegExp {
  return new RegExp(`(?<![${LETTER}])(?:${pattern})(?![${LETTER}])`, flags);
}

/**
 * Просторечие → нейтральное. Только целые слова и только там, где замена не
 * трогает падеж соседей. Список короткий намеренно: здесь то, что реально
 * пишут, а не то, что можно вообразить.
 */
const WORD_REPLACEMENTS: ReadonlyArray<[RegExp, string]> = [
  // Состояние техники
  [edge('не\\s+пашет|не\\s+фурычит'), 'не работает'],
  [edge('не\\s+пашут'), 'не работают'],
  [edge('сдох'), 'вышел из строя'],
  [edge('сдохла'), 'вышла из строя'],
  [edge('сдохло'), 'вышло из строя'],
  [edge('накрылся|полетел|крякнул'), 'вышел из строя'],
  [edge('накрылась|полетела|крякнула'), 'вышла из строя'],
  [edge('накрылось|полетело'), 'вышло из строя'],
  [edge('глючит|тупит|барахлит|косячит'), 'работает нестабильно'],
  // Итог
  [edge('вс[её]\\s+ок|вс[её]\\s+норм|вс[её]\\s+нормально'), 'всё исправно'],
  [edge('вс[её]\\s+пашет|вс[её]\\s+работает'), 'работает исправно'],
  [edge('работает\\s+нормально'), 'работает исправно'],
  // Действия — глагол на глагол того же управления, падеж дополнения цел
  [edge('поменял'), 'заменил'],
  [edge('поменяли'), 'заменили'],
  [edge('почистил'), 'очистил'],
  [edge('почистили'), 'очистили'],
  [edge('продул'), 'очистил продувкой'],
  [edge('подкрутил'), 'отрегулировал'],
  [edge('прошил'), 'обновил программное обеспечение'],
  [edge('сделал'), 'выполнил'],
  [edge('посмотрел'), 'осмотрел'],
  [edge('запустил'), 'ввёл в работу'],
];

/**
 * Слова, с которых начинается «а вот что я сделал». Перед ними ставим границу
 * мысли, даже если инженер не поставил ни точки, ни запятой.
 *
 * ⚠️ ЗДЕСЬ ТОЛЬКО ОСНОВЫ БЕЗ ХВОСТОВОЙ «Л». Граница мысли ищет «основа + …л»
 * (см. `splitClauses`), поэтому целое слово «заказал» этой «л» приписать
 * неоткуда — и граница молча не ставилась. Итог был скверный: «не греет
 * вообще заказал плату жду поставку» целиком уезжало в «Диагноз», и клиент
 * читал в акте про поломку то, что инженер СДЕЛАЛ. Поймано пробой на живых
 * фразах, не тестами.
 *
 * «привёз» и «отвёз» формы на «л» не имеют вовсе — они работают только как
 * начало клаузы, границу собой не открывают. Это осознанно: подходящего
 * признака у них нет.
 */
const ACTION_STEMS =
  'замен|поменя|очист|почист|промы|перепая|припая|пая|настро|отрегулир|подкрут|подтяну|смаз|устан|постав|сня|разобра|собра|прош|обнов|отремонт|почин|восстанов|запуст|вв[её]|провер|прове|выполн|сдела|проду|калибр|откалибр|заправ|зали|подключ|отключ|отсоедин|присоедин|зачист|обжа|заказ|прив[её]з|' +
  // Выезд и осмотр — это тоже работа, а не диагноз. Без них «приехал
  // посмотрел ничего не нашёл» уезжало в «Диагноз» из-за слов «не нашёл».
  'приеха|прибы|выеха|осмотре|посмотре|диагностир|вскры|забра|отв[её]з|верну';

/** Слова об итоге: «работает», «всё ок». */
const RESULT_STEMS = 'работает|заработал|заработала|исправ|протестир|норм|вс[её]';

/**
 * Слова, после которых слово об итоге НЕ начинает новую мысль.
 *
 * ⚠️ ИЗ-ЗА ОТСУТСТВИЯ ЭТОГО СПИСКА ЛОМАЛАСЬ САМАЯ ЧАСТАЯ ФРАЗА ИНЖЕНЕРА.
 * «Не работает» резалось пополам: «не» уходило отдельной мыслью (и попадало в
 * «Описание ремонта» обрывком «Не.»), а «работает» считалось сообщением об
 * успехе. Поломка при этом исчезала из диагноза начисто.
 *
 * Оговорки здесь по той же причине: «вроде норм» и «пока норм» слабее, чем
 * «норм». Отрезать оговорку — усилить сказанное инженером, то есть тоже
 * приписать ему чужие слова.
 */
const RESULT_GLUE = 'не|нет|вроде|пока|похоже|наверное|наверно|вс[её]';

/**
 * Слова о поломке. Ищем их ВНУТРИ клаузы, а не только в начале: инженер пишет
 * «плата сгорела» — подлежащее впереди, а признак поломки вторым словом.
 */
const PROBLEM_STEMS =
  'не\\s|нет\\s|сгор|перегор|слома|неиспр|отсутств|порва|пот[её]к|пот[её]чь|теч[её]т|течь|подтека|пробит|треснул|залип|заклин|шумит|гремит|греется|перегрев|окисл|засор|забит|разряд|села|сел|битый|дефект|повреж|отвал|отош[её]л|люфт|скрип|мигает|моргает|выбива|коротит|замыка|сдох|накрыл|полетел|крякнул|гл[юу]чит|тупит|барахлит|вышел\\s+из\\s+строя|вышла\\s+из\\s+строя';

/**
 * ⚠️ КАЖДЫЙ НАБОР ОБЯЗАН БЫТЬ В СВОЕЙ ГРУППЕ `(?:…)`.
 *
 * Без неё `a|b|c[а-я]*` означает «a, или b, или c с хвостом» — хвост цепляется
 * только к ПОСЛЕДНЕЙ ветке. Из-за этого `сгор` требовал слова ровно «сгор»,
 * «сгорела» не находилось, и поломка молча уезжала в описание работ. Поймано
 * пробой на живых фразах, тесты этого не показывали.
 */
const ACTION_START = new RegExp(`^\\s*(?:${ACTION_STEMS})[${LETTER}]*`, 'i');
const RESULT_START = new RegExp(`^\\s*(?:${RESULT_STEMS})[${LETTER}]*`, 'i');
const PROBLEM_ANYWHERE = edge(`(?:${PROBLEM_STEMS})[${LETTER}]*`, 'i');
/** «работает нестабильно» — это поломка, а не итог, хотя начинается как итог. */
const UNSTABLE = /работает\s+нестабильно|не\s+работает/i;

/** Союзы и вводные, которые остаются висеть на краях после разреза. */
const EDGE_NOISE = /^(?:и|а|но|потом|затем|далее|там|вот|ну|же|тоже|также)\s+|\s+(?:и|а|но)$/gi;

/**
 * Клауза целиком из вводных слов — выбрасываем.
 *
 * «подтянул разъем, вроде норм» резалось перед словом об итоге, и в «Описании
 * ремонта» оставалось предложение «Вроде.». В акте, который подписывает
 * клиент, это выглядит как небрежность — а смысла не несёт вовсе.
 */
const FILLER = 'вроде|пока|так|там|вот|ну|же|типа|короче|наверное|наверно|похоже|вообще|вс[её]';
const FILLER_ONLY = new RegExp(`^(?:${FILLER})(?:\\s+(?:${FILLER}))*$`, 'i');

/**
 * ⚠️ ЗДЕСЬ БЫЛА ГОТОВАЯ ФРАЗА «Оборудование протестировано, работоспособность
 * восстановлена.» — и она УБРАНА. Оставлено как предупреждение не вернуть.
 *
 * Её дописывал любой намёк на итог: «норм», «всё». В результате
 * «жду запчасть, пока норм» превращалось в акт, где сказано, что оборудование
 * ПРОТЕСТИРОВАНО и работоспособность ВОССТАНОВЛЕНА, — два утверждения, которых
 * инженер не делал, под подписью клиента. А «не работает» (самая частая фраза
 * вообще) давало «Не. Оборудование протестировано…».
 *
 * Теперь слова инженера об итоге идут в текст как есть, причёсанные словарём:
 * «всё пашет» → «Работает исправно». Это ровно то, что он сказал. Своих
 * утверждений в акт не добавляем НИКОГДА — красиво напишет модель.
 */

/**
 * Расставить границы мыслей там, где инженер их не поставил.
 *
 * Знаки препинания оставляем как есть, а перед словом-действием и словом об
 * итоге дописываем точку. Без этого «плата сгорела поменял всё пашет» —
 * одна клауза, и поломка с работой уезжают в одно поле.
 */
export function splitClauses(text: string): string[] {
  const marked = text
    // Только ГЛАГОЛ прошедшего времени (…л/ла/ло/ли) начинает новую мысль.
    // Иначе «заказал плату жду поставку» резалось перед существительным
    // «поставку» (основа «постав») и превращалось в «…жду. Поставку.».
    .replace(edge(`(?:${ACTION_STEMS})[${LETTER}]*л[аои]?`), (m) => `. ${m}`)
    // Слово об итоге начинает новую мысль — но НЕ после отрицания и оговорки
    // (см. RESULT_GLUE): «не работает» — это одна мысль, и она про поломку.
    .replace(
      new RegExp(
        `(?<!(?:${RESULT_GLUE})\\s)(?<![${LETTER}])(?:${RESULT_STEMS})[${LETTER}]*(?![${LETTER}])`,
        'gi',
      ),
      (m) => `. ${m}`,
    );
  return marked
    .split(/[.;!?\n]+|,\s*/)
    .map((s) => s.trim().replace(EDGE_NOISE, '').trim())
    .filter(
      (s) => s.length > 0 && new RegExp(`[${LETTER}\\d]`).test(s) && !FILLER_ONLY.test(s),
    );
}

export type ClauseKind = 'problem' | 'action' | 'result';

/**
 * К чему относится клауза.
 *
 * Порядок проверок важен. «Работает нестабильно» начинается со слова об итоге,
 * но говорит о поломке — иначе жалоба «глючит» потерялась бы вовсе: клаузы вида
 * «итог» в поля не попадают, они лишь разрешают дописать фразу о проверке.
 *
 * Непонятное считаем работой: в «Описании ремонта» лишняя строка портит текст,
 * а в «Диагнозе» — вводит в заблуждение о состоянии техники.
 */
export function classifyClause(clause: string): ClauseKind {
  const c = clause.trim();
  if (UNSTABLE.test(c)) return 'problem';
  if (RESULT_START.test(c)) return 'result';
  if (ACTION_START.test(c)) return 'action';
  if (PROBLEM_ANYWHERE.test(c)) return 'problem';
  return 'action';
}

/** Просторечие → нейтральное. Зовём ПОСЛЕ разбора: подсказки ищут живые слова. */
function normalizeWords(text: string): string {
  let out = text;
  for (const [re, to] of WORD_REPLACEMENTS) out = out.replace(re, to);
  return out;
}

/** Первая буква заглавная, в конце точка. Пустое остаётся пустым. */
function asSentence(s: string): string {
  const t = normalizeWords(s).trim().replace(/\s+/g, ' ');
  if (!t) return '';
  const head = t.charAt(0).toUpperCase() + t.slice(1);
  return /[.!?]$/.test(head) ? head : `${head}.`;
}

function joinSentences(parts: string[]): string | null {
  const sentences = parts.map(asSentence).filter(Boolean);
  return sentences.length > 0 ? sentences.join(' ') : null;
}

/**
 * Разложить написанное инженером на два поля наряда.
 *
 * В ответе только слова инженера, приведённые в порядок, плюс одна стандартная
 * фраза о проверке — и та лишь если инженер сам написал, что после ремонта
 * работает. Дописать её к «жду запчасть» значило бы соврать в акте.
 */
export function composeFromNotes(raw: string): ComposedNotes {
  const text = (raw ?? '').trim();
  if (!text) return { diagnosis: null, repairDescription: null };

  const problems: string[] = [];
  const actions: string[] = [];

  for (const clause of splitClauses(text)) {
    const kind = classifyClause(clause);
    // Итог — это слова инженера о состоянии техники ПОСЛЕ работы. Место им в
    // «Описании ремонта», своими словами. Раньше они выбрасывались, а взамен
    // дописывалась наша фраза — см. предупреждение выше.
    if (kind === 'problem') problems.push(clause);
    else actions.push(clause);
  }

  return {
    diagnosis: joinSentences(problems),
    repairDescription: joinSentences(actions),
  };
}

