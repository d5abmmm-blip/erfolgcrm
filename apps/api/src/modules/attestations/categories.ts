/**
 * Stage 10'.I — Справочник категорий аттестации инженеров.
 *
 * Хранится массивом в коде (а не отдельной таблицей в БД), потому что:
 *  - редкие изменения (1-2 раза в год при появлении новых типов техники);
 *  - не требует CRUD из UI;
 *  - даёт жёсткий контроль на уровне TS (тип ATTESTATION_CATEGORIES — единый источник истины).
 *
 * В БД храним свободный varchar(100) — на случай редких категорий вне справочника
 * (например, специфичный тип оборудования у одного клиента).
 */
export const ATTESTATION_CATEGORIES = [
  'Узкое медицинское оборудование (узи, эндоскопия)',
  'Лабораторное оборудование',
  'Стерилизационное оборудование',
  'Стоматологическое оборудование',
  'Хирургическое оборудование',
  'Анестезиологическое оборудование',
  'Реанимационное оборудование',
  'Рентгенологическое оборудование',
  'Электрокардиография и мониторинг',
  'Прочее медицинское оборудование',
] as const;

export type AttestationCategory = (typeof ATTESTATION_CATEGORIES)[number];

/** Узнать, входит ли строка в стандартный справочник (для UI-валидации). */
export function isKnownCategory(value: string): value is AttestationCategory {
  return (ATTESTATION_CATEGORIES as readonly string[]).includes(value);
}
