-- Вторая половина работы, начатой миграцией 0078 (там были ПДн клиентов).
--
-- ЗАЧЕМ. То же, что и в 0078: ключ PII_ENCRYPTION_KEY лежит в .env на ТОМ ЖЕ сервере,
-- что и база, поэтому от её кражи не защищает, а его потеря делает переписку нечитаемой
-- навсегда. Плюс у почты есть своя, отдельная беда: поиск.
--
-- ПОЧЕМУ ПОЧТА ХУЖЕ ОСТАЛЬНОГО. Фильтр поиска вынужден расшифровывать КАЖДУЮ строку,
-- и запрос выполняется ДВАЖДЫ (страница + счётчик). Замер: ~0.9 мс на строку, то есть
-- 5000 писем ≈ 9 секунд ожидания на каждый ввод в строке поиска. Из-за этой же цены
-- поле «От кого» в поиск сознательно НЕ добавляли (комментарий в email/repository.ts).
-- После переезда ограничение снимается: и поиск дешёвый, и «От кого» можно вернуть.
--
-- ЧТО ЭТА МИГРАЦИЯ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ.
-- Делает: добавляет пустые открытые колонки рядом с шифрованными.
-- НЕ делает: не переносит данные и НЕ удаляет шифрованные колонки.
--   Перенос — тот же скрипт `pnpm --filter @erfolg/db decrypt-pii`, в нём добавлен
--   раздел по письмам. Удаление старых колонок — отдельной миграцией-уборкой.
--
-- NOT NULL снимать не надо: все семь колонок и так были nullable (миграции 0042/0045).
--
-- ⚠️ ПОРЯДОК ВЫКАТА — ТОТ ЖЕ, ЧТО У 0078, И ОН ЗДЕСЬ ВАЖЕН.
--   1. бэкап базы;
--   2. git reset --hard origin/main;
--   3. build api web            (работающие контейнеры пока не трогаются);
--   4. МИГРАЦИЯ разовым контейнером — появляются пустые колонки;
--   5. `pnpm --filter @erfolg/db decrypt-pii` разовым контейнером — колонки наполняются;
--   6. up -d api web            — новый код встаёт на УЖЕ заполненные колонки.
