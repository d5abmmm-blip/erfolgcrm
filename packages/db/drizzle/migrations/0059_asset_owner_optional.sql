-- Владелец-клиент у единицы техники становится НЕОБЯЗАТЕЛЬНЫМ.
-- Раньше owner_client_id был NOT NULL — нельзя было завести оборудование «само по себе»
-- (например, собственный парк сервиса, демо-аппараты, техника на складе до продажи).
-- Теперь его можно оставить пустым (галочка «без привязки к клиенту» в форме).
--
-- Внешний ключ assets_owner_client_id_fkey (ON DELETE RESTRICT) ОСТАЁТСЯ: при NULL он
-- просто не проверяется, а удалить клиента, у которого ЕСТЬ техника, по-прежнему нельзя.

ALTER TABLE "assets" ALTER COLUMN "owner_client_id" DROP NOT NULL;
