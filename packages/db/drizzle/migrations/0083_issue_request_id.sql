-- Идемпотентный реплей списания со склада (офлайн-очередь).
--
-- Сценарий: «Списать со склада» дошло до сервера, партии списаны — а ответ
-- потерялся (мобильная сеть в подвале больницы). Клиент считает это сетевым
-- сбоем, кладёт мутацию в офлайн-очередь, и реплей списывает ВТОРОЙ раз:
-- остаток и себестоимость задваиваются.
--
-- client_request_id — ключ одного запроса списания. Клиент генерирует его в
-- момент действия (crypto.randomUUID) и повторяет тот же ключ при реплее.
-- Одному запросу соответствует ГРУППА движений (FEFO может списать несколько
-- партий), поэтому индекс НЕ уникальный: сервер перед списанием проверяет
-- «этот ключ уже применён?» под advisory-замком (см. issueToWorkOrderInTx).
--
-- NULL — движение создано без ключа: десктоп, ручные операции, приходы,
-- возвраты и вся история до этой миграции. Ничего не бэкфилим.

ALTER TABLE "inventory_movements" ADD COLUMN IF NOT EXISTS "client_request_id" uuid;

CREATE INDEX IF NOT EXISTS "inventory_movements_client_request_idx"
  ON "inventory_movements" ("tenant_id", "client_request_id")
  WHERE "client_request_id" IS NOT NULL;
