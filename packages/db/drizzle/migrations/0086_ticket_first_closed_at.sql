-- Дата первого закрытия заявки — чтобы переоткрытие не удваивало зарплату.
--
-- ЗАЧЕМ. Ведомость ЗП набирает строки работ по месяцу закрытия заявки
-- (payroll/repository.ts), а отметки «за эту работу уже заплатили» в базе нет.
-- Колонка `closed_at` живёт под проверкой
-- `(status = 'closed') = (closed_at IS NOT NULL)`, поэтому при переоткрытии она
-- обязана обнулиться, а повторное закрытие ставит СЕГОДНЯШНЮЮ дату. Те же самые
-- строки работ во второй раз попадали в ведомость нового месяца: заявку закрыли
-- в августе и заплатили, в сентябре директор переоткрыл её и закрыл заново —
-- платим ещё раз, и заметить это некому.
--
-- `first_closed_at` заполняется ТОЛЬКО у переоткрытых заявок. У всех остальных
-- он остаётся NULL, и месяц берётся из `closed_at` как раньше, поэтому ни один
-- существующий отчёт своих чисел не меняет.

ALTER TABLE "tickets" ADD COLUMN IF NOT EXISTS "first_closed_at" timestamptz;

-- Разовое восстановление истории по журналу событий: если в ленте заявки есть
-- переход в «Закрыта» РАНЬШЕ, чем нынешний closed_at, значит её переоткрывали, и
-- настоящее первое закрытие — самое раннее такое событие.
--
-- Условие `< closed_at - 1 minute` защищает от двух случаев: событие, записанное
-- в одной транзакции с закрытием (разница в миллисекунды — это не переоткрытие),
-- и перенесённые заявки, у которых события созданы в момент прогона импорта,
-- то есть заведомо ПОЗЖЕ исторической даты закрытия.
UPDATE "tickets" t
   SET "first_closed_at" = e.first_closed
  FROM (
        SELECT "ticket_id", MIN("created_at") AS first_closed
          FROM "ticket_events"
         WHERE "type" = 'status_change'
           AND "payload" ->> 'to' = 'closed'
         GROUP BY "ticket_id"
       ) e
 WHERE e."ticket_id" = t."id"
   AND t."closed_at" IS NOT NULL
   AND t."first_closed_at" IS NULL
   AND e.first_closed < t."closed_at" - interval '1 minute';
