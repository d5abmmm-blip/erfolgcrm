// Юрлицо / бюджетник по названию.
// ВАЖНО: \b в JS не работает с кириллицей, поэтому границу слова задаём через (?<!\p{L})…(?!\p{L}) с флагом u.
export const LEGAL_RE =
  /(?<!\p{L})(ООО|ОАО|ЗАО|ПАО|АО|ИП|ГБУ|ФГБУ|ФГКУ|ГАУ|ГКУ|ГУП|МУП|НКО|ЧУЗ|НУЗ|ЧОУ|ФКУ|ФБУ|МБУ|ГБОУ|ФГБОУ|МБОУ|ОГБУ|КГБУ|МБДОУ|ДОУ|УБ|ГБ|РБ|РКБ|ЦРБ|РДКБ|ДКБ|РКЦ|ПЦ|ФАП|СББЖ)(?!\p{L})|больниц|поликлин|диспансер|госпит|клиник|медицин|медцентр|аптек|лаборатор|санатор|роддом|перинатал|стоматолог|ветеринар|комиссариат|салон|центр/iu;

// ФИО физлица → инициалы для display_name: «Иванов Иван Иванович» → «Иванов И.И.».
// Полное ФИО хранится ТОЛЬКО в зашифрованной колонке full_name_encrypted; display_name
// (plaintext, индексируется) обязан быть инициалами — иначе ПДн физлица утекают открытым
// текстом мимо шифрования (см. schema clients.ts) и попадают в бэкапы. Формат совпадает с
// buildDisplayNameFromFio в apps/api clients/router.ts (источник правды при создании через UI).
export function initialsDisplayName(fio: string): string {
  const parts = fio.trim().split(/\s+/).filter(Boolean);
  if (parts.length <= 1) return (parts[0] ?? '').slice(0, 200);
  const surname = parts[0]!;
  const initials = parts
    .slice(1)
    .map((p) => `${p[0]!.toUpperCase()}.`)
    .join('');
  return `${surname} ${initials}`.slice(0, 200);
}

/**
 * Юрлицо или физлицо. Порядок сигналов: название организации (LEGAL_RE) → CLIENTTYPE=1 →
 * ИНН ЮРЛИЦА → папка «Бюджетные» (root=4). Папка «Частные лица» делает физлицом только
 * если название НЕ похоже на организацию (LEGAL_RE не сработал).
 *
 * IMP-1: ИНН считается признаком юрлица ТОЛЬКО при длине 10 цифр (ИНН организации).
 * Личный ИНН физлица/ИП — 12 цифр, это персональные данные; он НЕ должен сам по себе
 * переводить клиента в ветку 'legal', иначе физлицо с заполненным ИНН попадает в юрлица и
 * его ФИО/адрес/телефон/ИНН пишутся в ОТКРЫТЫЕ колонки мимо шифрования и инициалов.
 * ИП, названный «ИП Иванов», всё равно ловится LEGAL_RE и остаётся юрлицом.
 */
export function classifyClientType(args: {
  name: string;
  clientTypeOld: number | null;
  inn: string | null;
  root: number | null;
}): 'legal' | 'individual' {
  const legalInn = (args.inn?.replace(/\D/g, '').length ?? 0) === 10;
  if (LEGAL_RE.test(args.name) || args.clientTypeOld === 1 || legalInn || args.root === 4) {
    return 'legal';
  }
  return 'individual';
}
