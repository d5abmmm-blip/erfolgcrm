/**
 * ЕДИНСТВЕННОЕ ОПРЕДЕЛЕНИЕ «запись перенесена из старой системы» на всю систему.
 *
 * Импорт из WinServisePro (packages/db/src/import-winservice.ts и
 * import-repair-archive.ts) выдаёт записям детерминированные идентификаторы
 * **версии 5** — sha1 от неизменного ключа старой базы. Всё, что заводит сама CRM,
 * получает идентификатор версии 4 (`gen_random_uuid()` в БД) или 7. Версия записана
 * в 15-м символе строки: `xxxxxxxx-xxxx-Vxxx-...`.
 *
 * Признак проверен на копии боевой базы 2026-08-15 — расхождений НЕТ ни одного:
 *
 * | таблица           | всего | версия 5 |
 * |-------------------|-------|----------|
 * | tickets           |  5999 |     5999 |
 * | work_orders       |  5999 |     5999 |
 * | assets            |  5044 |     5044 |
 * | work_order_lines  |  2331 |     2331 |
 * | clients           |   664 |      664 |
 * | repair_archive    |  4267 |     4267 |
 * | users (перенос)   |    19 |       19 |
 *
 * В контрольной базе, где ВСЕ 3008 строк заведены самим приложением, записей
 * версии 5 нет ни одной — ложных срабатываний признак не даёт.
 *
 * Почему не по дате: у клиентов, техники, строк работ и учёток `created_at` равен
 * моменту прогона импорта (2026-07-07), а не старой дате, — по дате их отличить
 * НЕЛЬЗЯ. Дата работает только для заявок и нарядов.
 *
 * ⚠️ Признак используется ТОЛЬКО чтобы ПОМЕТИТЬ запись, а не чтобы её спрятать.
 * На импортированных данных держится вся себестоимость системы, типы техники,
 * графики ТО, гарантии, выгрузка в 1С и история клиента. Прятать их нельзя —
 * подробности в apps/api/src/lib/legacy-origin.ts.
 */

/** Позиция символа версии в каноничной записи идентификатора (0-based). */
const VERSION_CHAR_INDEX = 14;

/**
 * Запись перенесена из старой системы?
 *
 * Принимает идентификатор строкой. Пустое значение и мусор — «нет»: неизвестное
 * происхождение не повод рисовать человеку пометку, которой он не поверит.
 */
export function isLegacyId(id: string | null | undefined): boolean {
  return typeof id === 'string' && id.length > VERSION_CHAR_INDEX && id[VERSION_CHAR_INDEX] === '5';
}

/**
 * Номер заявки или наряда из старой системы. Импорт ставит префикс `WSP-`
 * (import-winservice.ts), CRM — `T-2026-000001` / `WO-...`. Годится там, где
 * идентификатора под рукой нет, а номер есть.
 */
export function isLegacyNumber(value: string | null | undefined): boolean {
  return typeof value === 'string' && value.startsWith('WSP-');
}

/** Подпись пометки. Одно слово на весь интерфейс, чтобы не расползлось синонимами. */
export const LEGACY_LABEL = 'из старой системы';

/** Короткая подпись для узких мест (строка таблицы, чип). */
export const LEGACY_LABEL_SHORT = 'перенос';

